#!/usr/bin/env bash
set -euo pipefail
shopt -s nullglob

ROOT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
TMP_DIR="$(mktemp -d)"
trap 'rm -rf -- "$TMP_DIR"' EXIT

source "$ROOT_DIR/system-dns.sh"

BIN_DIR="$TMP_DIR/bin"
mkdir -p "$BIN_DIR"
cat > "$BIN_DIR/dig" <<'MOCK'
#!/bin/sh
case "${DNS_TEST_PROBE_MODE:-success}" in
  success)
    printf '%s\n' "$@" > "$DNS_TEST_DIG_ARGS_LOG"
    printf 'youtube.com. 60 IN A 142.250.72.14\n'
    exit 0
    ;;
  zero-address)
    printf 'youtube.com. 60 IN A 0.0.0.0\n'
    exit 0
    ;;
  no-answer)
    printf ';; communications error to 127.0.0.1#53: SERVFAIL\n'
    exit 0
    ;;
esac
MOCK
cat > "$BIN_DIR/chattr" <<'MOCK'
#!/bin/sh
operation="$1"
file="$2"
printf '%s %s\n' "$operation" "$file" >> "$DNS_TEST_CHATTR_LOG"
case "$operation" in
  +i)
    case "${DNS_TEST_LOCK_MODE:-success}" in
      fail) exit 1 ;;
      fail-once)
        if [ ! -e "$DNS_TEST_FAILED_ONCE" ]; then
          : > "$DNS_TEST_FAILED_ONCE"
          exit 1
        fi
        ;;
    esac
    : > "$DNS_TEST_LOCK_STATE"
    ;;
  -i)
    [ "${DNS_TEST_UNLOCK_MODE:-success}" != fail ] || exit 1
    rm -f "$DNS_TEST_LOCK_STATE"
    ;;
  *) exit 2 ;;
esac
MOCK
cat > "$BIN_DIR/lsattr" <<'MOCK'
#!/bin/sh
file="$2"
flags='----------------------'
[ ! -f "$DNS_TEST_LOCK_STATE" ] || flags='----i-----------------'
printf '%s %s\n' "$flags" "$file"
MOCK
cat > "$BIN_DIR/systemctl" <<'MOCK'
#!/bin/sh
printf '%s\n' "$*" >> "$DNS_TEST_SYSTEMCTL_LOG"
case "$1" in
  is-active)
    [ "${DNS_TEST_SYSTEMD_MODE:-success}" != inactive ]
    ;;
  is-enabled)
    [ -f "$DNS_TEST_SYSTEMD_ENABLED" ]
    ;;
  enable)
    [ "${DNS_TEST_SYSTEMD_MODE:-success}" != fail-enable ] || exit 1
    : > "$DNS_TEST_SYSTEMD_ENABLED"
    ;;
  *) exit 2 ;;
esac
MOCK
chmod +x "$BIN_DIR/dig" "$BIN_DIR/chattr" "$BIN_DIR/lsattr" "$BIN_DIR/systemctl"

new_case() {
  local name="$1"
  CASE_DIR="$TMP_DIR/$name"
  mkdir -p "$CASE_DIR"
  RESOLV="$CASE_DIR/resolv.conf"
  DNS_TEST_LOCK_STATE="$CASE_DIR/locked"
  DNS_TEST_CHATTR_LOG="$CASE_DIR/chattr.log"
  DNS_TEST_DIG_ARGS_LOG="$CASE_DIR/dig-args.log"
  DNS_TEST_FAILED_ONCE="$CASE_DIR/failed-once"
  DNS_TEST_SYSTEMD_ENABLED="$CASE_DIR/systemd-enabled"
  DNS_TEST_SYSTEMCTL_LOG="$CASE_DIR/systemctl.log"
  : > "$DNS_TEST_CHATTR_LOG"
  : > "$DNS_TEST_SYSTEMCTL_LOG"
  rm -f "$DNS_TEST_LOCK_STATE"
}

run_activate() {
  PATH="$BIN_DIR:/usr/bin:/bin" \
    DNS_TEST_LOCK_STATE="$DNS_TEST_LOCK_STATE" \
    DNS_TEST_CHATTR_LOG="$DNS_TEST_CHATTR_LOG" \
    DNS_TEST_DIG_ARGS_LOG="$DNS_TEST_DIG_ARGS_LOG" \
    DNS_TEST_FAILED_ONCE="$DNS_TEST_FAILED_ONCE" \
    DNS_TEST_SYSTEMD_ENABLED="$DNS_TEST_SYSTEMD_ENABLED" \
    DNS_TEST_SYSTEMCTL_LOG="$DNS_TEST_SYSTEMCTL_LOG" \
    DNS_TEST_SYSTEMD_MODE="${DNS_TEST_SYSTEMD_MODE:-success}" \
    DNS_TEST_PROBE_MODE="${DNS_TEST_PROBE_MODE:-success}" \
    DNS_TEST_LOCK_MODE="${DNS_TEST_LOCK_MODE:-success}" \
    DNS_TEST_UNLOCK_MODE="${DNS_TEST_UNLOCK_MODE:-success}" \
    system_dns_activate "$RESOLV" "${DNS_TEST_DOMAIN:-youtube.com}" "${DNS_TEST_DIG_COMMAND:-dig}" "${DNS_TEST_SYSTEMCTL_COMMAND:-systemctl}"
}

# An effective direct SmartDNS answer must precede replacement and immutable locking.
new_case success
cat > "$RESOLV" <<'CONF'
# generated by systemd-resolved
nameserver 1.1.1.1
nameserver 1.0.0.1
search example.net
options edns0
CONF
cp "$RESOLV" "$CASE_DIR/original"
run_activate > "$CASE_DIR/output.txt" 2>&1
[[ -f "$DNS_TEST_LOCK_STATE" ]]
[[ -f "$DNS_TEST_SYSTEMD_ENABLED" ]]
grep -q '^enable smartdns$' "$DNS_TEST_SYSTEMCTL_LOG"
grep -q '^nameserver 127\.0\.0\.1$' "$RESOLV"
! grep -q '^[[:space:]]*nameserver[[:space:]]\+1\.' "$RESOLV"
grep -q '^search example\.net$' "$RESOLV"
grep -q '^options edns0$' "$RESOLV"
grep -q '@127.0.0.1' "$DNS_TEST_DIG_ARGS_LOG"
grep -q 'youtube.com' "$DNS_TEST_DIG_ARGS_LOG"
backup=("$RESOLV".smartdns-app-dns.bak.*)
[[ ${#backup[@]} -eq 1 ]]
[[ -f "${backup[0]}" ]]
cmp "$CASE_DIR/original" "${backup[0]}"
grep -q '^+i ' "$DNS_TEST_CHATTR_LOG"

# A different local DNS daemon must not satisfy the check when SmartDNS itself is inactive.
new_case inactive-service
printf 'nameserver 9.9.9.9\n' > "$RESOLV"
cp "$RESOLV" "$CASE_DIR/original"
DNS_TEST_SYSTEMD_MODE=inactive
if run_activate > "$CASE_DIR/output.txt" 2>&1; then
  echo 'Expected activation to fail when smartdns.service is inactive.' >&2
  exit 1
fi
unset DNS_TEST_SYSTEMD_MODE
cmp "$CASE_DIR/original" "$RESOLV"
backup=("$RESOLV".smartdns-app-dns.bak.*)
[[ ${#backup[@]} -eq 0 ]]
[[ ! -s "$DNS_TEST_DIG_ARGS_LOG" ]]

# SERVFAIL/no answer must leave the original resolver untouched and must not lock it.
new_case probe-failure
printf 'nameserver 9.9.9.9\noptions timeout:2\n' > "$RESOLV"
cp "$RESOLV" "$CASE_DIR/original"
DNS_TEST_PROBE_MODE=no-answer
if run_activate > "$CASE_DIR/output.txt" 2>&1; then
  echo 'Expected the SmartDNS probe to reject SERVFAIL/no-answer.' >&2
  exit 1
fi
unset DNS_TEST_PROBE_MODE
cmp "$CASE_DIR/original" "$RESOLV"
[[ ! -e "$DNS_TEST_LOCK_STATE" ]]
backup=("$RESOLV".smartdns-app-dns.bak.*)
[[ ${#backup[@]} -eq 0 ]]

new_case zero-address
printf 'nameserver 8.8.4.4\n' > "$RESOLV"
cp "$RESOLV" "$CASE_DIR/original"
DNS_TEST_PROBE_MODE=zero-address
if run_activate > "$CASE_DIR/output.txt" 2>&1; then
  echo 'Expected an all-zero DNS answer to be rejected.' >&2
  exit 1
fi
unset DNS_TEST_PROBE_MODE
cmp "$CASE_DIR/original" "$RESOLV"
[[ ! -e "$DNS_TEST_LOCK_STATE" ]]

# Missing dig is fail-closed; never redirect the machine to an unverified resolver.
new_case missing-dig
printf 'nameserver 8.8.8.8\n' > "$RESOLV"
cp "$RESOLV" "$CASE_DIR/original"
DNS_TEST_DIG_COMMAND=definitely-not-installed
if run_activate > "$CASE_DIR/output.txt" 2>&1; then
  echo 'Expected activation to fail when no DNS probe command is available.' >&2
  exit 1
fi
unset DNS_TEST_DIG_COMMAND
cmp "$CASE_DIR/original" "$RESOLV"
[[ ! -e "$DNS_TEST_LOCK_STATE" ]]

# If immutable locking fails, restore the original resolver instead of leaving an unlocked redirect.
new_case lock-failure
printf 'nameserver 4.4.4.4\nsearch old.example\n' > "$RESOLV"
cp "$RESOLV" "$CASE_DIR/original"
DNS_TEST_LOCK_MODE=fail
if run_activate > "$CASE_DIR/output.txt" 2>&1; then
  echo 'Expected activation to fail when chattr +i fails.' >&2
  exit 1
fi
unset DNS_TEST_LOCK_MODE
cmp "$CASE_DIR/original" "$RESOLV"
[[ ! -e "$DNS_TEST_LOCK_STATE" ]]
grep -q '^-i ' "$DNS_TEST_CHATTR_LOG"

# If an original immutable resolver had to be temporarily unlocked, rollback restores its lock.
new_case prelocked-rollback
printf 'nameserver 4.2.2.2\n' > "$RESOLV"
cp "$RESOLV" "$CASE_DIR/original"
: > "$DNS_TEST_LOCK_STATE"
DNS_TEST_LOCK_MODE=fail-once
if run_activate > "$CASE_DIR/output.txt" 2>&1; then
  echo 'Expected activation to fail on the first lock attempt.' >&2
  exit 1
fi
unset DNS_TEST_LOCK_MODE
cmp "$CASE_DIR/original" "$RESOLV"
[[ -f "$DNS_TEST_LOCK_STATE" ]]

# If an existing immutable lock cannot be changed, preserve its backup and never unlock silently.
new_case unlock-failure
printf 'nameserver 4.4.4.4\n' > "$RESOLV"
cp "$RESOLV" "$CASE_DIR/original"
: > "$DNS_TEST_LOCK_STATE"
DNS_TEST_UNLOCK_MODE=fail
DNS_TEST_LOCK_MODE=fail
if run_activate > "$CASE_DIR/output.txt" 2>&1; then
  echo 'Expected activation to fail when the existing immutable file cannot be safely unlocked.' >&2
  exit 1
fi
unset DNS_TEST_UNLOCK_MODE DNS_TEST_LOCK_MODE
cmp "$CASE_DIR/original" "$RESOLV"
[[ -f "$DNS_TEST_LOCK_STATE" ]]
backup=("$RESOLV".smartdns-app-dns.bak.*)
[[ ${#backup[@]} -eq 1 ]]
cmp "$CASE_DIR/original" "${backup[0]}"

# If the service cannot be enabled for boot, restore the original resolver.
new_case enable-failure
printf 'nameserver 8.8.8.8\n' > "$RESOLV"
cp "$RESOLV" "$CASE_DIR/original"
DNS_TEST_SYSTEMD_MODE=fail-enable
if run_activate > "$CASE_DIR/output.txt" 2>&1; then
  echo 'Expected activation to fail when systemd cannot enable SmartDNS.' >&2
  exit 1
fi
unset DNS_TEST_SYSTEMD_MODE
cmp "$CASE_DIR/original" "$RESOLV"
[[ ! -e "$DNS_TEST_LOCK_STATE" ]]
[[ ! -e "$DNS_TEST_SYSTEMD_ENABLED" ]]

# Existing symlinked resolv.conf is backed up as a symlink before atomic replacement.
new_case symlink
TARGET="$CASE_DIR/resolved.conf"
printf 'nameserver 1.1.1.1\noptions edns0\n' > "$TARGET"
rm -f "$RESOLV"
ln -s "$TARGET" "$RESOLV"
run_activate > "$CASE_DIR/output.txt" 2>&1
[[ ! -L "$RESOLV" ]]
backup=("$RESOLV".smartdns-app-dns.bak.*)
[[ ${#backup[@]} -eq 1 && -L "${backup[0]}" ]]
grep -q '^nameserver 127\.0\.0\.1$' "$RESOLV"

# Non-applying modes do not request resolver activation.
system_dns_should_activate --youtube 45.202.246.167
for skip_arg in --no-restart --dry-run --list --help --install-only --no-system-dns; do
  if system_dns_should_activate "$skip_arg"; then
    printf 'Expected %s to skip system DNS activation.\n' "$skip_arg" >&2
    exit 1
  fi
done

echo 'PASS: activation requires active/enabled SmartDNS, a valid localhost DNS answer, and a verified immutable lock; failures preserve the prior resolver.'
